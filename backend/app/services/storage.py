"""File storage behind an interface: local disk in dev, S3-compatible in prod."""

from pathlib import Path
from typing import Protocol

from anyio import to_thread

from app.core.config import Settings


class Storage(Protocol):
    async def save(self, key: str, data: bytes) -> None: ...
    async def read(self, key: str) -> bytes: ...
    async def delete(self, key: str) -> None: ...


class LocalDiskStorage:
    def __init__(self, root: Path) -> None:
        self.root = root.resolve()

    def _path(self, key: str) -> Path:
        path = (self.root / key).resolve()
        # Keys are generated by us, but never trust a path with user input near it.
        if not path.is_relative_to(self.root):
            raise ValueError("storage key escapes the storage root")
        return path

    async def save(self, key: str, data: bytes) -> None:
        path = self._path(key)

        def write() -> None:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)

        await to_thread.run_sync(write)

    async def read(self, key: str) -> bytes:
        return await to_thread.run_sync(self._path(key).read_bytes)

    async def delete(self, key: str) -> None:
        await to_thread.run_sync(lambda: self._path(key).unlink(missing_ok=True))


def build_storage(settings: Settings) -> Storage:
    # An S3-compatible backend implements the same three methods. It is not
    # written yet: set up object storage and add it here before running more
    # than one server, since local disk is not shared between machines.
    return LocalDiskStorage(settings.upload_dir)
